#!/usr/bin/env bash

# Run the complete selective-QA experiment pipeline.
#
# The pipeline separates parameter selection from held-out evaluation:
#
#   CALIBRATION SPLIT
#       -> confidence estimation
#       -> temperature fitting
#       -> verifier signals for fusion-weight tuning
#
#   TEST SPLIT
#       -> frozen temperature application
#       -> verifier inference
#       -> final score ranking
#       -> AURC / matched-coverage evaluation
#       -> paired bootstrap uncertainty
#
# The canonical experiment uses LIMIT=3000. Smaller LIMIT values are treated as
# smoke runs and are written to separate output directories so they cannot
# overwrite the final experiment artifacts.


# Stop immediately on command failures, undefined variables, or failed commands
# inside pipelines. A scientific pipeline should never continue after a failed
# stage and silently combine incomplete and valid artifacts.
set -euo pipefail


# Resolve the repository root from this script's location so the experiment can
# be launched from any working directory.
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

cd "$PROJECT_ROOT"


# Allow Python commands launched below to import project modules directly from
# the repository.
export PYTHONPATH="$PROJECT_ROOT"


# Runtime controls.
#
# DEVICE controls model inference.
# LIMIT controls how many records are processed from each split.
# ORDER_SEED fixes nested-subset order and score-tie resolution.
# BOOTSTRAP_SAMPLES controls paired bootstrap repetitions.
DEVICE="${DEVICE:-cpu}"
LIMIT="${LIMIT:-3000}"
ORDER_SEED="${ORDER_SEED:-17}"
BOOTSTRAP_SAMPLES="${BOOTSTRAP_SAMPLES:-5000}"


# Reject malformed runtime settings before any expensive model inference starts.
if ! [[ "$LIMIT" =~ ^[1-9][0-9]*$ ]]; then
    echo "ERROR: LIMIT must be a positive integer. Received: $LIMIT" >&2
    exit 2
fi

if ! [[ "$ORDER_SEED" =~ ^[0-9]+$ ]]; then
    echo "ERROR: ORDER_SEED must be a non-negative integer. Received: $ORDER_SEED" >&2
    exit 2
fi

if ! [[ "$BOOTSTRAP_SAMPLES" =~ ^[1-9][0-9]*$ ]]; then
    echo \
        "ERROR: BOOTSTRAP_SAMPLES must be a positive integer. " \
        "Received: $BOOTSTRAP_SAMPLES" >&2
    exit 2
fi


# Canonical and smoke runs use different directories. This prevents a quick
# development run from overwriting publication-facing artifacts.
if [[ "$LIMIT" == "3000" ]]; then
    PRED_DIR="outputs/predictions"
    TABLE_DIR="outputs/tables"
    FINAL_EVAL_DIR="outputs/evaluation/final_sample_size_comparison"
else
    PRED_DIR="outputs/predictions/smoke_limit_${LIMIT}"
    TABLE_DIR="outputs/tables/smoke_limit_${LIMIT}"
    FINAL_EVAL_DIR="outputs/evaluation/smoke_limit_${LIMIT}"
fi


mkdir -p \
    "$PRED_DIR" \
    "$TABLE_DIR" \
    "$FINAL_EVAL_DIR"


# Resume expensive JSONL-producing stages when an artifact already contains the
# expected number of records.
#
# This is a convenience cache, not a proof that the artifact was generated by
# the current code version. After changing model/evaluation logic, stale
# prediction artifacts should be removed before performing a clean reproduction.
run_if_missing() {
    local output="$1"

    shift

    if [[ -f "$output" ]]; then
        local line_count

        line_count="$(
            wc -l < "$output" \
                | tr -d "[:space:]"
        )"

        if [[ "$line_count" == "$LIMIT" ]]; then
            echo \
                "✓ Exists with $line_count rows, " \
                "skipping: $output"

            return
        fi

        echo \
            "↻ Stale row count " \
            "($line_count != $LIMIT), regenerating: $output"

    else
        echo "→ Creating: $output"
    fi

    "$@"
}


echo "========================================"
echo "Final selective-QA experiment pipeline"
echo "Device: $DEVICE"
echo "Examples per split: $LIMIT"
echo "Deterministic order seed: $ORDER_SEED"
echo "Bootstrap samples: $BOOTSTRAP_SAMPLES"
echo "========================================"


# ---------------------------------------------------------------------------
# 1. Forced-answer QA candidates
# ---------------------------------------------------------------------------
#
# Generate QA predictions independently for calibration and held-out test data.
# The pretrained QA model is used as-is; this project does not fine-tune the
# backbone on either split.

run_if_missing \
    "$PRED_DIR/raw_baseline_calibration.jsonl" \
    python -m src.baselines.raw_answer_baseline \
        --split calibration \
        --limit "$LIMIT" \
        --device "$DEVICE"


run_if_missing \
    "$PRED_DIR/raw_baseline_test.jsonl" \
    python -m src.baselines.raw_answer_baseline \
        --split test \
        --limit "$LIMIT" \
        --device "$DEVICE"


# ---------------------------------------------------------------------------
# 2. Raw confidence estimation
# ---------------------------------------------------------------------------
#
# Estimate the QA model's answer-vs-null confidence signal before temperature
# calibration. Both splits receive the same score construction.

run_if_missing \
    "$PRED_DIR/raw_baseline_with_confidence_calibration.jsonl" \
    python -m src.verification.confidence_estimator \
        --input \
        "$PRED_DIR/raw_baseline_calibration.jsonl" \
        --output \
        "$PRED_DIR/raw_baseline_with_confidence_calibration.jsonl" \
        --device "$DEVICE"


run_if_missing \
    "$PRED_DIR/raw_baseline_with_confidence_test.jsonl" \
    python -m src.verification.confidence_estimator \
        --input \
        "$PRED_DIR/raw_baseline_test.jsonl" \
        --output \
        "$PRED_DIR/raw_baseline_with_confidence_test.jsonl" \
        --device "$DEVICE"


# ---------------------------------------------------------------------------
# 3. Temperature fitting — CALIBRATION ONLY
# ---------------------------------------------------------------------------
#
# Temperature is a fitted parameter. Calibration labels may therefore be used
# here, but test labels must not influence the fitted value.

CALIBRATED_CALIBRATION="$PRED_DIR/raw_baseline_calibrated_calibration.jsonl"


if [[ \
    -f "$CALIBRATED_CALIBRATION" \
    && -f "$TABLE_DIR/temperature_scaling_parameters.json" \
]]; then

    calibration_rows="$(
        wc -l < "$CALIBRATED_CALIBRATION" \
            | tr -d "[:space:]"
    )"

else
    calibration_rows=0
fi


if [[ "$calibration_rows" == "$LIMIT" ]]; then

    echo \
        "Calibration parameters exist for " \
        "$calibration_rows rows, skipping temperature fitting."

else

    echo \
        "Fitting temperature on calibration split " \
        "($LIMIT rows)."

    python -m src.calibration.temperature_scaling \
        --input \
        "$PRED_DIR/raw_baseline_with_confidence_calibration.jsonl" \
        --output \
        "$CALIBRATED_CALIBRATION" \
        --parameters \
        "$TABLE_DIR/temperature_scaling_parameters.json"
fi


# ---------------------------------------------------------------------------
# 4. Frozen temperature application to TEST
# ---------------------------------------------------------------------------
#
# The temperature fitted above is now treated as fixed. Test labels are not
# consulted when transforming test confidence values.

run_if_missing \
    "$PRED_DIR/raw_baseline_calibrated_test.jsonl" \
    env \
        PRED_DIR="$PRED_DIR" \
        TABLE_DIR="$TABLE_DIR" \
    python -c '
import json
import os
from pathlib import Path

from src.calibration.temperature_scaling import apply_temperature
from src.utils.io import load_jsonl, save_jsonl

parameter_path = (
    Path(os.environ["TABLE_DIR"])
    / "temperature_scaling_parameters.json"
)

input_path = (
    Path(os.environ["PRED_DIR"])
    / "raw_baseline_with_confidence_test.jsonl"
)

output_path = (
    Path(os.environ["PRED_DIR"])
    / "raw_baseline_calibrated_test.jsonl"
)

with parameter_path.open(
    "r",
    encoding="utf-8",
) as file:
    parameters = json.load(file)

temperature = float(
    parameters["temperature"]
)

predictions = load_jsonl(
    input_path
)

calibrated = apply_temperature(
    predictions,
    temperature,
)

save_jsonl(
    calibrated,
    output_path,
)

print(
    f"Applied frozen temperature: "
    f"{temperature:.6f}"
)

print(
    f"Test examples: "
    f"{len(calibrated)}"
)

print(
    f"Saved: "
    f"{output_path}"
)
'


# ---------------------------------------------------------------------------
# 5. Question-aware semantic verifier V2
# ---------------------------------------------------------------------------
#
# Add the question-aware NLI support signal to held-out QA candidates.
#
# Invalid generated claims follow the score behavior implemented inside the V2
# verifier itself; this orchestration script does not redefine that logic.

run_if_missing \
    "$PRED_DIR/test_with_question_aware_semantic_v2.jsonl" \
    python -m src.verification.question_answer_nli_verifier_v2 \
        --input \
        "$PRED_DIR/raw_baseline_calibrated_test.jsonl" \
        --output \
        "$PRED_DIR/test_with_question_aware_semantic_v2.jsonl" \
        --batch-size 4


# ---------------------------------------------------------------------------
# 6. Answer-support / self verifier
# ---------------------------------------------------------------------------
#
# Add the second NLI-based verifier signal.
#
# This should be interpreted as another answer-support signal, not as an
# independently trained QA system.

run_if_missing \
    "$PRED_DIR/test_with_question_aware_v2_and_self_verification.jsonl" \
    python -m src.verification.self_verifier \
        --input \
        "$PRED_DIR/test_with_question_aware_semantic_v2.jsonl" \
        --output \
        "$PRED_DIR/test_with_question_aware_v2_and_self_verification.jsonl" \
        --batch-size 4


# ---------------------------------------------------------------------------
# 7. Final deterministic nested held-out evaluation
# ---------------------------------------------------------------------------
#
# For the canonical run:
#
#   200 ⊂ 500 ⊂ 1000 ⊂ 2000 ⊂ 3000
#
# One deterministic shuffled order is created using ORDER_SEED. Smaller sample
# sizes are prefixes of the same order rather than independent random samples.

if [[ "$LIMIT" == "3000" ]]; then
    SAMPLE_SIZES="200,500,1000,2000,3000"
else
    SAMPLE_SIZES="$LIMIT"
fi


echo \
    "Running deterministic evaluation for " \
    "sample sizes: $SAMPLE_SIZES"


python experiments/compare_question_aware_ablation_sample_sizes.py \
    --input \
    "$PRED_DIR/test_with_question_aware_v2_and_self_verification.jsonl" \
    --output-dir \
    "$FINAL_EVAL_DIR" \
    --sample-sizes \
    "$SAMPLE_SIZES" \
    --seed \
    "$ORDER_SEED" \
    --save-subsets


# ---------------------------------------------------------------------------
# 8. Paired bootstrap uncertainty
# ---------------------------------------------------------------------------
#
# Every bootstrap replicate resamples one set of example indices and evaluates
# all five ranking methods on that same sample. This makes the AURC differences
# relative to confidence-only paired within each replicate.

echo
echo "Running paired bootstrap AURC uncertainty analysis..."


python experiments/bootstrap_aurc_uncertainty.py \
    --input \
    "$PRED_DIR/test_with_question_aware_v2_and_self_verification.jsonl" \
    --output-dir \
    "$FINAL_EVAL_DIR/bootstrap" \
    --bootstrap-samples \
    "$BOOTSTRAP_SAMPLES" \
    --seed \
    "$ORDER_SEED" \
    --order-seed \
    "$ORDER_SEED"


# ---------------------------------------------------------------------------
# 9. Full-protocol analyses
# ---------------------------------------------------------------------------
#
# These stages are run only for the canonical N=3000 experiment. Smoke runs
# intentionally skip them.

if [[ "$LIMIT" == "3000" ]]; then

    # -----------------------------------------------------------------------
    # Native no-answer baseline
    # -----------------------------------------------------------------------
    #
    # This comparison lets the pretrained SQuAD2 model use its native no-answer
    # behavior rather than forcing every example to produce an answer.

    echo
    echo "Running native SQuAD2 no-answer baseline..."


    python -m src.baselines.native_no_answer_baseline \
        --split test \
        --limit "$LIMIT" \
        --device "$DEVICE"


    python -m \
        src.evaluation.evaluate_native_no_answer_baseline


    # -----------------------------------------------------------------------
    # Calibration-only verifier inference for fusion tuning
    # -----------------------------------------------------------------------
    #
    # Fusion alpha is a model-selection parameter. Verifier signals needed for
    # alpha tuning are therefore generated on calibration data, not test labels.

    echo
    echo \
        "Running verifier signals on calibration split " \
        "for fusion tuning..."


    run_if_missing \
        "$PRED_DIR/calibration_with_question_aware_semantic_evidence_v2.jsonl" \
        python -m \
            src.verification.question_answer_nli_verifier_v2 \
            --input \
            "$PRED_DIR/raw_baseline_calibrated_calibration.jsonl" \
            --output \
            "$PRED_DIR/calibration_with_question_aware_semantic_evidence_v2.jsonl" \
            --batch-size 4


    run_if_missing \
        "$PRED_DIR/calibration_with_question_aware_v2_and_self_verification.jsonl" \
        python -m src.verification.self_verifier \
            --input \
            "$PRED_DIR/calibration_with_question_aware_semantic_evidence_v2.jsonl" \
            --output \
            "$PRED_DIR/calibration_with_question_aware_v2_and_self_verification.jsonl" \
            --batch-size 4


    # -----------------------------------------------------------------------
    # Fusion-weight tuning
    # -----------------------------------------------------------------------
    #
    # Alpha is selected by minimum AURC on calibration data only and must be
    # frozen before interpreting held-out performance.

    echo
    echo "Tuning fusion weights on calibration split only..."


    python experiments/tune_fusion_weights.py


    # -----------------------------------------------------------------------
    # Held-out probability calibration evaluation
    # -----------------------------------------------------------------------
    #
    # These reports compare confidence calibration before and after applying the
    # already-fitted temperature.
    #
    # Test correctness labels are used here only for evaluation; they do not
    # modify the temperature parameter.

    echo
    echo "Evaluating held-out probability calibration..."


    python -m src.calibration.calibration_metrics \
        --input \
        "$PRED_DIR/raw_baseline_with_confidence_test.jsonl" \
        --output \
        "$TABLE_DIR/test_calibration_before.json" \
        --bins 10


    python -m src.calibration.calibration_metrics \
        --input \
        "$PRED_DIR/raw_baseline_calibrated_test.jsonl" \
        --output \
        "$TABLE_DIR/test_calibration_after.json" \
        --bins 10


    # -----------------------------------------------------------------------
    # Canonical final verifier error analysis
    # -----------------------------------------------------------------------
    #
    # Regenerate the lightweight held-out diagnostic summary from the final
    # prediction file using the same canonical forced-answer correctness
    # function as the main evaluation. This stage performs no model inference
    # and does not tune any experimental parameter.

    echo
    echo "Generating canonical final verifier error analysis..."

    python -m src.analysis.generate_final_error_analysis


    # -----------------------------------------------------------------------
    # Tie-aware rank diagnostics
    # -----------------------------------------------------------------------
    #
    # This analysis explains how the fixed verifier fusions alter
    # correct-vs-incorrect pair ordering. It is explanatory only and does not
    # tune parameters on the held-out set.

    echo
    echo "Running rank-flip analysis..."


    python experiments/analyze_rank_flips.py
fi


echo
echo "========================================"
echo "FINAL EXPERIMENT PIPELINE COMPLETE"
echo "========================================"
echo "Final predictions:"
echo "$PRED_DIR/test_with_question_aware_v2_and_self_verification.jsonl"
echo
echo "Final evaluation:"
echo "$FINAL_EVAL_DIR"